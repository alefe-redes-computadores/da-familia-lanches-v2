import assert from "node:assert/strict";
import fs from "node:fs";
import { createRequire } from "node:module";
import vm from "node:vm";
const require = createRequire(import.meta.url);
const ts = require("typescript");
const source = fs.readFileSync("src/lib/thermalReceipt.ts", "utf8");
const printer = fs.readFileSync("src/lib/printOrder.ts", "utf8");
const htmlExample = {id:"r5-calibration-1949", userName:"Cliente QA", tipoEntrega:"delivery", total:34.5, metodoPagamento:"pix", deliverySnapshot:{street:"Rua Longa do Teste",number:"1500",district:"Patos"},itens:[{name:"Lanche especial com queijo",quantity:1,selectedAddons:[],observation:"Sem cebola"}]};
const compiled = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={exports:{}};
const sandbox={module:mod,exports:mod.exports,Intl,Date,String,Number,require(id){
  if(id==="./adminOrderAddress")return {adminOrderAddress:(o)=>({full:o.deliverySnapshot?`${o.deliverySnapshot.street}, ${o.deliverySnapshot.number} — ${o.deliverySnapshot.district}`:""})};
  if(id==="./orderCompat")return {getOrderItems:o=>o.itens||[],paymentLabel:v=>String(v).toUpperCase(),orderDateToDate:v=>v?new Date(v):null};
  throw new Error(`Import inesperado: ${id}`);
}};
vm.runInNewContext(compiled,sandbox);
const build=mod.exports.buildThermalReceiptHtml;
const h58=build(htmlExample,"58"),h80=build(htmlExample,"80");
const check=(label,condition)=>{assert.ok(condition,`R5: ${label}`);console.log("✓",label);};
check("renderização 58 mm mantém perfil 48 mm",h58.includes('data-profile="58"')&&h58.includes('[data-profile="58"] .receipt { width: 48mm; }'));
check("renderização 80 mm mantém perfil 68 mm",h80.includes('data-profile="80"')&&h80.includes('[data-profile="80"] .receipt { width: 68mm; }'));
check("teste curto usa as duas bordas",h58.includes('class="border-test"')&&h58.includes('INÍCIO')&&h58.includes('DIR.'));
check("botão de calibração não imprime automaticamente",h58.includes('id="dfl-calibrate"')&&h58.includes('calibrationButton.addEventListener'));
check("alternar modo muda somente conteúdo do papel",h58.includes("setAttribute('data-mode'")&&h58.includes("'calibration':'ticket'"));
check("a impressão exige clique no botão",h58.includes("printButton.addEventListener('click',function(){window.print();})"));
check("sem impressão no carregamento",!h58.includes('window.onload=function(){window.print()')&&!printer.includes('window.print'));
check("sem corte por comando ESC/POS",!source.includes('GS V')&&!source.includes('ESC i')&&!h58.includes('window.close()'));
check("ticket de produção permanece intacto",h58.includes('Lanche especial com queijo')&&h58.includes('Rua Longa do Teste')&&h58.includes('R$'));
check("prévia mantém ação de impressão",h58.includes('Imprimir após conferir'));
check("instrução manual de driver preservada",h58.includes('Configure')||h58.includes('Ajuste o tamanho da mídia'));
check("teste possui aviso de impressão manual",h58.includes('Imprimir SOMENTE teste curto'));
console.log('DFL V85.1 R5 — PRÉ-VOO USB: 12 CONTRATOS OK');
