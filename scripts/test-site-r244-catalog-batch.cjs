function load(file,deps={}){
  const source=read(file);
  const ast=ts.createSourceFile(file,source,ts.ScriptTarget.Latest,true,file.endsWith('tsx')?ts.ScriptKind.TSX:ts.ScriptKind.TS);
  ok(ast.parseDiagnostics.length===0,'syntax '+file);
  const compiled=ts.transpileModule(source,{fileName:file,reportDiagnostics:true,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true}});
  ok(!(compiled.diagnostics||[]).some(d=>d.category===ts.DiagnosticCategory.Error),'transpile '+file);
  const mod={exports:{}};
  new Function('require','module','exports',compiled.outputText)(key=>{
    if(!Object.prototype.hasOwnProperty.call(deps,key))throw Error('R244 unexpected import '+key+' in '+file);
    return deps[key];
  },mod,mod.exports);
  return mod.exports;
}
