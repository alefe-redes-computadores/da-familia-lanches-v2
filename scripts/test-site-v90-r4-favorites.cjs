'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const ts=require(path.join(process.cwd(),'node_modules/typescript'));
const source=fs.readFileSync('src/lib/savedProductIds.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const local=new Map();let events=0,deny=false,removed=0;
const win={localStorage:{getItem:k=>local.get(k)??null,setItem:(k,v)=>{if(deny)throw Error('blocked');local.set(k,v)},removeItem:k=>{if(deny)throw Error('blocked');removed++;local.delete(k)}},dispatchEvent:()=>{events++}};
const exp={};vm.runInNewContext(js,{module:{exports:exp},exports:exp,window:win,Event:class{},JSON,Array,Set},{filename:'favorites.mock.cjs'});
assert.equal(exp.toggleSavedProductId('combo-test'),true);
assert.equal(exp.toggleSavedProductId('outro'),true);
assert.deepEqual(Array.from(exp.readSavedProductIds()),['outro','combo-test']);
const before=events;
assert.equal(exp.clearSavedProductIds(),true);
assert.deepEqual(Array.from(exp.readSavedProductIds()),[]);
assert.equal(events,before+1,'Limpeza notifica outros componentes');
assert.ok(removed>=1);
assert.equal(exp.toggleSavedProductId('combo-test'),true);
deny=true;const oldEvents=events;
assert.equal(exp.clearSavedProductIds(),false,'Storage bloqueado não gera falsa confirmação');
assert.equal(events,oldEvents,'Falha não dispara atualização enganosa');
const home=fs.readFileSync('src/app/page.tsx','utf8'),css=fs.readFileSync('src/app/page.module.css','utf8');
assert.ok(home.includes('clearFavoritesConfirm &&'),'Confirmação em duas etapas');
assert.ok(home.includes('if (clearSavedProductIds()) setClearFavoritesConfirm(false);'),'Fecha confirmação somente em sucesso');
assert.ok(css.includes('.savedConfirm button:focus-visible'),'Acessibilidade teclado');
console.log('V90 R4: limpar salvos com confirmação e recuperação de storage — 12 contratos OK');
