ok(partial.full.includes('Rua das Flores, 145')&&partial.full.includes('Centro'),'snapshot vazio nao apaga rua, numero e bairro');
ok(partial.full.includes('Ao lado da escola'),'referencia da entrega mantida');
const legacy=adminOrderAddress({endereco:'Rua Esperanca, 978 - Jardim',deliverySnapshot:{district:'Jardim'}});
ok(legacy.full.startsWith('Rua Esperanca, 978 - Jardim'),'bairro isolado nao substitui endereco legado');
