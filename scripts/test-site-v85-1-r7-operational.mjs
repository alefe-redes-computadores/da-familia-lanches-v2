import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const read=p=>fs.readFileSync(p,'utf8');
const load=p=>{
  const src=read(p);
  const {outputText,diagnostics}=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022},reportDiagnostics:true});
  assert.equal(diagnostics?.filter(d=>d.category===ts.DiagnosticCategory.Error).length||0,0,`tipagem sintatica ${p}`);
  const module={exports:{}};
  new Function('module','exports',outputText)(module,module.exports);
  return module.exports;
};
const ok=(condition,label)=>{assert.ok(condition,`R7: ${label}`);console.log('✓',label);};
const {DEFAULT_STORE_SETTINGS,normalizeStoreSettings,evaluateStoreStatus}=load('src/lib/storeSchedule.ts');
const {adminOrderAddress}=load('src/lib/adminOrderAddress.ts');
const sp=(date)=>new Date(date);
ok(!DEFAULT_STORE_SETTINGS.schedule.mon.enabled&&!DEFAULT_STORE_SETTINGS.schedule.tue.enabled&&!DEFAULT_STORE_SETTINGS.schedule.wed.enabled,'fallback de segunda a quarta permanece fechado');
ok(DEFAULT_STORE_SETTINGS.schedule.thu.enabled&&DEFAULT_STORE_SETTINGS.schedule.sun.enabled,'quinta e domingo preservados como abertura padrao');
ok(!evaluateStoreStatus(DEFAULT_STORE_SETTINGS,sp('2026-10-26T21:30:00Z')).isOpen,'segunda 18h30 Brasilia: fallback fechado');
ok(!evaluateStoreStatus(DEFAULT_STORE_SETTINGS,sp('2026-10-28T21:30:00Z')).isOpen,'quarta 18h30 Brasilia: fallback fechado');
ok(evaluateStoreStatus(DEFAULT_STORE_SETTINGS,sp('2026-10-22T21:30:00Z')).isOpen,'quinta 18h30 Brasilia: fallback aberto');
const custom=normalizeStoreSettings({mode:'auto',schedule:{mon:{enabled:true,open:'17:00',close:'21:00'}}});
ok(custom.schedule.mon.enabled&&custom.schedule.mon.open==='17:00','configuracao manual existente no Firestore vence fallback');
ok(evaluateStoreStatus(custom,sp('2026-10-26T21:30:00Z')).isOpen,'segunda abre se documento salvo a habilitar');
ok(evaluateStoreStatus({...DEFAULT_STORE_SETTINGS,mode:'force_open'},sp('2026-10-26T21:30:00Z')).isOpen,'abertura manual preservada');
