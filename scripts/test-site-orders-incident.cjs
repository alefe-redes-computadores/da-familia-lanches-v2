'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ts=require(path.resolve('node_modules/typescript'));
const source=fs.readFileSync('src/app/api/orders/route.ts','utf8');
const ast=ts.createSourceFile('route.ts',source,ts.ScriptTarget.Latest,true,ts.ScriptKind.TS);
const names=['stripUndefinedOrderFields','safeOrderFailureKind'];
const declarations=ast.statements.filter(s=>ts.isFunctionDeclaration(s)&&names.includes(s.name?.text));
assert.equal(declarations.length,2,'Ambas as funcoes reais precisam existir');
const js=ts.transpileModule(declarations.map(n=>n.getText(ast)).join('\n'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const f=new Function(js+'\nreturn {stripUndefinedOrderFields,safeOrderFailureKind}');
const {stripUndefinedOrderFields:clean,safeOrderFailureKind:kind}=f();
const stamp=new Date('2026-10-25T20:00:00Z');
const sample={id:'produto',price:17,option:undefined,child:{a:null,optional:undefined,q:2},addons:[{id:'a',price:1,comment:undefined}],stamp};
const result=clean(sample);
assert.deepEqual(result,{id:'produto',price:17,child:{a:null,q:2},addons:[{id:'a',price:1}],stamp});
assert.equal(result.stamp,stamp);
assert.equal(clean(undefined),undefined);
assert.equal(kind(new Error('Cannot use undefined as a Firestore value')),'INVALID_UNDEFINED_FIELD');
assert.equal(kind(new Error('resource exhausted')),'FIRESTORE_QUOTA');
assert.equal(kind(new Error('permission denied')),'PERMISSION_OR_CREDENTIAL');
assert.equal(kind(new Error('unknown issue')),'UNCLASSIFIED_SERVER_EXCEPTION');
assert(source.includes('itens: canonicalItems.map(stripUndefinedOrderFields), subtotal, taxaEntrega: fee,'));
assert(source.includes('tx.create(orderRef, canonicalOrder)'));
assert(source.includes('tx.create(adminDb.collection(INTEGRATION_COLLECTIONS.outbox)'));
assert(source.includes('requestFingerprint') && source.includes('clientRequestId'));
assert(source.includes('cents(total) !== cents(Number(incoming.total))'));
assert(source.includes('validAddonSelection(product,line.selectedAddons.length)'));
assert(source.includes('[orders/create] exception_category'));
const parse=ts.transpileModule(source,{fileName:'route.ts',reportDiagnostics:true,compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}});
assert.equal((parse.diagnostics||[]).filter(d=>d.category===ts.DiagnosticCategory.Error).length,0,'Sintaxe TS');
