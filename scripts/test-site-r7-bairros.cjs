'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const src=fs.readFileSync('src/lib/addressIntelligence.ts','utf8');
const js=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const obj={exports:{}};
new Function('module','exports',js)(obj,obj.exports);
const {suggestDistricts,matchDeliveryRate,inspectDistrict}=obj.exports;
const configured=['São José Operário','São Francisco','Centro','Jardim América'];
assert.equal(suggestDistricts('Sao Jsoe Operario',configured)[0],'São José Operário');
assert.equal(suggestDistricts('Sao Jose Operario',configured).includes('São José Operário'),false);
assert.ok(suggestDistricts('Jardim',configured).includes('Jardim América'),'bairro configurado deve constar nas sugestoes');
assert.equal(inspectDistrict('Jardim',configured).valid,false,'entrada ambigua nao pode ser considerada bairro completo');
assert.deepEqual(suggestDistricts('Sa'),[]);
assert.equal(matchDeliveryRate('Sao Jsoe Operario',[{nome:'São José Operário',taxa:9}]),undefined);
assert.equal(inspectDistrict('Sao J',configured).valid,false);
assert.equal(matchDeliveryRate('São José Operário',[{nome:'São José Operário',taxa:9}]).taxa,9);
assert.equal(src.includes('fetch('),false);
console.log('R7 bairros: fuzzy, acentos, toque, sem frete por aproximacao: OK');
