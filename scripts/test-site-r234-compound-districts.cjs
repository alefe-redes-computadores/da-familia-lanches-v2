const cache=new Map();
function loadTS(path){
  if(cache.has(path))return cache.get(path);
  const input=rd(path);
  const ast=ts.createSourceFile(path,input,ts.ScriptTarget.Latest,true,ts.ScriptKind.TS);
  assert.equal(ast.parseDiagnostics.length,0,`${path}: invalid TS source`);
  const js=ts.transpileModule(input,{fileName:path,compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
  const module={exports:{}};cache.set(path,module.exports);
  new Function('require','module','exports',js)((p)=>{
    if(p==='@/lib/addressIntelligence')return loadTS('src/lib/addressIntelligence.ts');
    throw Error('R234 unexpected dependency: '+p);
  },module,module.exports);
  return module.exports;
}
