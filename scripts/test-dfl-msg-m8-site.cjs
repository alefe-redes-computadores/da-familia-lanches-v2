#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const component='src/components/admin/MessagingCenterAdmin.tsx';
const css='src/components/admin/MessagingCenterAdmin.module.css';
const ui=fs.readFileSync(component,'utf8');
const style=fs.readFileSync(css,'utf8');
let passed=0;
const check=(condition,title)=>{assert.ok(condition,title);passed++;};
check(ts.createSourceFile(component,ui,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX).parseDiagnostics.length===0,'UI valid TSX');
check(ui.includes("useState<'orders' | 'messages'>('orders')"),'default por pedido');
check(ui.includes("const orders = useMemo(() =>")&&ui.includes('new Map<string,'),'agrupar mensagens da amostra');
check(ui.includes('expandedOrder===group.id')&&ui.includes('aria-expanded'),'expandir timeline acessível');
check(ui.includes('eventLabels[item.event]')&&ui.includes('statusLabels[item.status]'),'eventos e estados legíveis');
check(ui.includes("setView('orders')")&&ui.includes("setView('messages')"),'modos por pedido e por mensagem');
check(ui.includes('item.retry.explanation')&&ui.includes('item.retry.remaining'),'motivo e tentativas permanecem');
check(ui.includes("fetch('/api/admin/messaging/retry'")&&ui.includes('confirmRetry === item.id'),'retry seguro não removido');
check(ui.includes('Ferramentas avançadas')&&ui.includes('<details className={styles.advanced}>'),'diagnostico recolhido');
check(ui.includes("onClick={() => void inspectBridges()}")&&ui.includes("fetch('/api/admin/messaging-readiness'"),'diagnóstico por ação');
check(ui.includes('Fila não é confirmação de entrega.')&&ui.includes('não confirma entrega no WhatsApp'),'sem alegação falsa de entrega');
check(ui.includes('data.truncated')&&ui.includes('data.limit'),'limites da amostra claros');
check(ui.includes('setData(result)')&&!ui.includes('setData(null)'),'falha preserva dados anteriores');
check(!/useEffect\s*\(|onSnapshot\s*\(|setInterval\s*\(/.test(ui),'sem polling/listeners');
check(!ui.includes("fetch('/api/integration/")&&!ui.includes('EVOLUTION_API_KEY'),'nenhum provedor direto do frontend');
check(style.includes('.orderCard')&&style.includes('.viewTabs')&&style.includes('.advanced'),'visual progressivo');
check(style.includes('@media(max-width:700px)')&&style.includes('prefers-reduced-motion'),'responsividade e menos movimento');
check(ui.includes('gerenciamento oficial no Admin'),'nao cria autoridade comercial paralela');
console.log(`MSG-M8 SITE: ${passed} contratos isolados OK; zero rede e zero WhatsApp.`);
